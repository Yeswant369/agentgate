"""Generate the seeded scenario fixtures as YAML.

The fixtures are committed so the scenario set is inspectable and version-
controlled, and any drift shows up in a diff. Regenerate with:
  python -m evals.dump_fixtures
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import yaml  # noqa: E402

from evals.scenarios import all_scenarios, scenario_to_dict  # noqa: E402

OUT = Path(__file__).resolve().parent / "scenarios.yaml"


def main() -> None:
    scenarios = all_scenarios()
    payload = {
        "meta": {
            "count": len(scenarios),
            "legit": sum(1 for s in scenarios if s.klass == "legit"),
            "attacks": sum(1 for s in scenarios if s.klass != "legit"),
            "attack_classes": sorted({s.klass for s in scenarios if s.klass != "legit"}),
            "note": "Generated by evals/dump_fixtures.py — do not edit by hand.",
        },
        "scenarios": [scenario_to_dict(s) for s in scenarios],
    }
    OUT.write_text(yaml.safe_dump(payload, sort_keys=False, width=100))
    print(f"wrote {len(scenarios)} scenarios to {OUT}")


if __name__ == "__main__":
    main()
